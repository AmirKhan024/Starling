"""scripts/build_world_floorplan.py
-----------------------------------
Generates, from configs/world/warehouse.yaml (the single source of truth
for the live 3D world):

  * data/floorplan/warehouse_world.geojson — walkable floor, obstacles, and
    each camera's ZONE, computed from what that camera can actually see
    (starling_world.layout.compute_camera_zones);
  * configs/calib/world/node-0N.yaml — each camera's calibration (K, R, t
    and the image->floor homography), in the same cv2.FileStorage format
    scripts/calibrate_homography.py writes for a physical camera;
  * docs/world_coverage.png — a coverage map (which camera sees which cell,
    and how many pixels tall a person is there);
  * configs/nodes/world/node-0N.yaml — the four world-camera node configs
    (each node's coverage ROI is its computed zone; node 0 also gets the
    entrance gate it verifies employees at).

Usage:
    python scripts/build_world_floorplan.py [--config configs/world/warehouse.yaml]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "packages"))

import numpy as np  # noqa: E402
from starling_world.config import load_world_config  # noqa: E402
from starling_world.layout import (  # noqa: E402
    cameras,
    compute_camera_zones,
    write_floorplan_geojson,
)

_ZONE_RGB = {0: (66, 133, 244), 1: (52, 168, 83), 2: (251, 188, 5), 3: (234, 67, 53)}


def render_coverage_png(cfg, out: Path, scale: int = 8) -> None:
    from PIL import Image, ImageDraw

    zones, free, px = compute_camera_zones(cfg)
    h, w = free.shape
    img = np.full((h, w, 3), 60, dtype=np.uint8)
    img[free] = (236, 236, 236)
    for n, m in zones.items():
        strength = np.clip(px[n] / 160.0, 0.35, 1.0)
        rgb = np.array(_ZONE_RGB.get(n, (120, 120, 120)), dtype=float)
        for c in range(3):
            chan = img[..., c]
            chan[m] = (255 - (255 - rgb[c]) * strength[m]).astype(np.uint8)
    im = Image.fromarray(img).resize((w * scale, h * scale), Image.NEAREST)
    d = ImageDraw.Draw(im)
    for n, cam in cameras(cfg).items():
        x, y = cam.mount[0] / cfg.navmesh_cell_m * scale, cam.mount[1] / cfg.navmesh_cell_m * scale
        d.ellipse([x - 7, y - 7, x + 7, y + 7], fill=(20, 20, 20))
        d.text((x + 9, y - 6), f"CAM-{n}", fill=(20, 20, 20))
    out.parent.mkdir(parents=True, exist_ok=True)
    im.save(out)


# Ring topology (CLAUDE.md rule 4): each node gossips to its two neighbours
# only — the cameras in the adjacent corners: NW(0) - NE(1) - SE(3) - SW(2).
_RING = {0: (2, 1), 1: (0, 3), 3: (1, 2), 2: (3, 0)}
_BASE_PORT = 5555
# ROC-calibrated on held-out live-world renders: see
# docs/results_world_perception.md (scripts/calibrate_world_appearance.py).
_SIM_THRESHOLD = 0.70


def _roi_of(zone_feature) -> list[list[float]]:
    from shapely.geometry import shape

    g = shape(zone_feature["geometry"])
    biggest = g if g.geom_type == "Polygon" else max(g.geoms, key=lambda p: p.area)
    return [[round(x, 3), round(y, 3)] for x, y in list(biggest.exterior.coords)[:-1]]


def write_node_configs(cfg, floorplan: dict, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    zones = {
        f["properties"]["node_id"]: f
        for f in floorplan["features"]
        if f["properties"].get("role") == "camera_zone"
    }
    gate = cfg.entrance.gate
    for cam in cfg.cameras:
        n = cam.node_id
        a, b = _RING[n]
        roi = _roi_of(zones[n])
        gate_block = (
            f"""  gate: {{x: {gate.x}, y: {gate.y}, radius_m: {gate.radius_m}}}   # the entrance gate this camera verifies employees at
"""  # noqa: E501 (generated YAML)
            if n == gate.node_id
            else "  gate: null\n"
        )
        text = f"""# Starling node config — node-{n:02d} (WORLD variant: its camera is the live 3D
# world's "{cam.name}" camera). GENERATED by scripts/build_world_floorplan.py
# from configs/world/warehouse.yaml — edit that file and rebuild, not this one.
# Every threshold has a documented default in packages/starling_node/config.py.

node_id: {n}
name: "node-{n:02d}"

# The literal string "world": apps/node.py receives this camera's JPEG frames
# from the world server and runs real perception on them (_run_world).
source: "world"
is_chokepoint: {"true" if n == gate.node_id else "false"}

db_path: "data/nodes/world/node-{n:02d}/local.db"
calib_path: "configs/calib/world/node-{n:02d}.yaml"   # floor homography for this camera

stream_epoch: 0.0

perception:
  yolo_model: "yolo11s.pt"   # see docs/results_world_perception.md for why not the nano model
  conf: 0.15                 # low: ByteTrack keeps a track alive on weak detections; new tracks still need 0.25
  embed_dim: 96              # starling_perception.appearance: 6 stripes x (12 hue + 4 value) bins

world:
  connect_endpoint: "{cfg.endpoints.frames_bind}"
  fps: {cfg.camera_frames.fps}
  imgsz: 512
  torch_threads: 3
  registry_path: "data/world/employee_registry.json"   # every camera recognises enrolled employees
{gate_block}
match:
  # ROC-CALIBRATED on held-out renders of the live world (cross-camera pairs,
  # score = similarity x quality): docs/results_world_perception.md.
  sim_threshold: {_SIM_THRESHOLD}
  threshold_source: "ROC-CALIBRATED (scripts/calibrate_world_appearance.py, live 3D world)"
  margin_threshold: 0.10
  gate_extra_slack_m: 0.6   # foot-point noise (median 0.19 m, p90 0.33 m) at 3 claims/s
  # A verified/recognised employee's anchor absorbs the unnamed hypothesis the
  # same person had before it (starling_crdt.resolver._adopt_unanchored).
  anchor_adopt_radius_m: 2.0
  anchor_adopt_max_age_s: 10.0
  # Two cameras naming one person at the same instant differ by their combined
  # position error: not a conflict (starling_crdt.resolver).
  anchor_continue_slack_m: 2.0
  lost_threshold_s: 120.0
  ema_alpha: 0.10

net:
  listen_port: {_BASE_PORT + n}
  neighbours: ["127.0.0.1:{_BASE_PORT + a}", "127.0.0.1:{_BASE_PORT + b}"]  # ring topology (CLAUDE.md rule 4)
  gossip_interval_s: 2.0

geometry:
  navmesh_path: "{cfg.floorplan_path}"
  cell_size_m: {cfg.navmesh_cell_m}

coverage:
  # This camera's own zone (largest piece), as computed from what it can see.
  roi_polygon: {roi}
  watched_boundary_ids: []
  tau_attest: 0.7
  background_alpha: 0.02
  bg_diff_threshold: 30.0
  blob_area_threshold: 120   # pixels in the quarter-resolution coverage frame

attest:
  tick_interval_s: 2.0
  tau_attest: 0.7

plausibility:
  # C2 x C4: a claim inside another camera's zone that that camera confidently
  # attested empty is a lie (starling_consensus.contradiction).
  attested_absence_check: true

attack:
  attack: "none"
  intensity: 0.0
  enable_control_endpoint: true
  control_bind_host: "127.0.0.1"
"""  # noqa: E501 (generated YAML)
        (out_dir / f"node-{n:02d}.yaml").write_text(text, encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--config", type=Path, default=REPO / "configs" / "world" / "warehouse.yaml")
    ap.add_argument("--calib-dir", type=Path, default=REPO / "configs" / "calib" / "world")
    ap.add_argument("--no-png", action="store_true")
    args = ap.parse_args(argv)

    cfg = load_world_config(args.config)
    data = write_floorplan_geojson(cfg, REPO / cfg.floorplan_path)
    print(f"wrote {cfg.floorplan_path}: {data['stats']}")  # CLI banner

    args.calib_dir.mkdir(parents=True, exist_ok=True)
    for n, cam in cameras(cfg).items():
        calib = cam.calibration()
        path = args.calib_dir / f"node-{n:02d}.yaml"
        calib.to_yaml(path)
        print(
            f"wrote {path.relative_to(REPO)} (reprojection error {calib.reprojection_error:.2e} px)"
        )  # CLI banner

    write_node_configs(cfg, data, REPO / "configs" / "nodes" / "world")
    print("wrote configs/nodes/world/node-0N.yaml")  # CLI banner

    if not args.no_png:
        render_coverage_png(cfg, REPO / "docs" / "world_coverage.png")
        print("wrote docs/world_coverage.png")  # CLI banner
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
